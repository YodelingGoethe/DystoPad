//! Interface texts. A missing German text doesn't compile, because both languages fill the same struct.

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Eq, Debug, Default)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    #[default]
    En,
    De,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::En, Lang::De];

    pub fn name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::De => "Deutsch",
        }
    }

    pub fn dict(self) -> &'static Dict {
        match self {
            Lang::En => &EN,
            Lang::De => &DE,
        }
    }
}

/// Fills `{0}`, `{1}`, … in a text.
pub fn fill(text: &str, args: &[&dyn std::fmt::Display]) -> String {
    args.iter().enumerate().fold(text.to_owned(), |s, (i, a)| {
        s.replace(&format!("{{{i}}}"), &a.to_string())
    })
}

